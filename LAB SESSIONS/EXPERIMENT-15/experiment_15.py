import cv2
import numpy as np
from google.colab import files
import matplotlib.pyplot as plt

# Upload image
uploaded = files.upload()
image_path = list(uploaded.keys())[0]

# Read image
img = cv2.imread(image_path)

# Convert BGR to RGB for display
img_rgb = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)

# Get image dimensions
h, w = img.shape[:2]

# Source points (corners of original image)
src_pts = np.array([
    [0, 0],
    [w-1, 0],
    [w-1, h-1],
    [0, h-1]
], dtype=np.float32)

# Destination points
dst_pts = np.array([
    [50, 50],
    [w-100, 20],
    [w-50, h-80],
    [80, h-30]
], dtype=np.float32)

# -------- Direct Linear Transformation (DLT) --------
A = []

for i in range(4):
    x, y = src_pts[i]
    u, v = dst_pts[i]

    A.append([-x, -y, -1, 0, 0, 0, x*u, y*u, u])
    A.append([0, 0, 0, -x, -y, -1, x*v, y*v, v])

A = np.array(A)

# Solve using SVD
U, S, Vt = np.linalg.svd(A)

# Last row of V gives homography
H = Vt[-1].reshape(3, 3)

# Normalize
H = H / H[2, 2]

# Apply perspective transformation
dlt_img = cv2.warpPerspective(img, H, (w, h))

# Save output
cv2.imwrite("DLT_Transformed_Image.jpg", dlt_img)

# Convert to RGB
dlt_rgb = cv2.cvtColor(dlt_img, cv2.COLOR_BGR2RGB)

# Display
plt.figure(figsize=(10,5))

plt.subplot(1,2,1)
plt.imshow(img_rgb)
plt.title("Original Image")
plt.axis("off")

plt.subplot(1,2,2)
plt.imshow(dlt_rgb)
plt.title("DLT Transformed Image")
plt.axis("off")

plt.show()

# Download output
files.download("DLT_Transformed_Image.jpg")