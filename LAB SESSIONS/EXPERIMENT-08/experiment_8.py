import cv2
from google.colab import files
from google.colab.patches import cv2_imshow

# Upload image
uploaded = files.upload()

# Get uploaded image name
image_path = next(iter(uploaded))

# Read image
image = cv2.imread(image_path)

# Get image dimensions
height, width = image.shape[:2]

# Enlarge image
bigger_image = cv2.resize(image, (int(width * 3), int(height * 3)))

# Shrink image
smaller_image = cv2.resize(image, (int(width * 0.5), int(height * 0.5)))

# Display images
print("Original Image")
cv2_imshow(image)

print("Bigger Image")
cv2_imshow(bigger_image)

print("Smaller Image")
cv2_imshow(smaller_image)

# Save images
cv2.imwrite("Bigger_image.jpg", bigger_image)
cv2.imwrite("Smaller_image.jpg", smaller_image)

# Download the saved images
files.download("Bigger_image.jpg")
files.download("Smaller_image.jpg")