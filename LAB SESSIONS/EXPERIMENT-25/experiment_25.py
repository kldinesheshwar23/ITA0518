import cv2
import numpy as np
from google.colab import files
from google.colab.patches import cv2_imshow

# Upload image
uploaded = files.upload()

# Get uploaded file name
filename = next(iter(uploaded))

# Read image
image = cv2.imread(filename)

# Check image
if image is None:
    print("Error: Image could not be loaded.")
else:
    # Convert to grayscale
    gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)

    # Calculate Sobel gradients
    gradient_x = cv2.Sobel(
        gray, cv2.CV_64F, dx=1, dy=0, ksize=3
    )

    gradient_y = cv2.Sobel(
        gray, cv2.CV_64F, dx=0, dy=1, ksize=3
    )

    # Subtract gradients
    gradient = cv2.subtract(gradient_x, gradient_y)

    # Convert result to displayable 8-bit image
    gradient = cv2.convertScaleAbs(gradient)

    # Display original image
    print("Original Image:")
    cv2_imshow(image)

    # Display Sobel gradient result
    print("Sobel Gradient Image:")
    cv2_imshow(gradient)

    # Save output
    cv2.imwrite("/content/sharpened_image3.jpg", gradient)

    print("Output saved as sharpened_image3.jpg")