import cv2
from google.colab import files
from matplotlib import pyplot as plt

# Upload image
uploaded = files.upload()

# Get uploaded file name
image_path = list(uploaded.keys())[0]

# Read image
img = cv2.imread(image_path)

# Check if image is loaded
if img is None:
    print("Error: Image not found!")
else:
    # Rotate clockwise
    rotated_clockwise = cv2.rotate(img, cv2.ROTATE_90_CLOCKWISE)

    # Rotate counterclockwise
    rotated_counterclockwise = cv2.rotate(img, cv2.ROTATE_90_COUNTERCLOCKWISE)

    # Save images
    cv2.imwrite("rotated_clockwise.jpg", rotated_clockwise)
    cv2.imwrite("rotated_counterclockwise.jpg", rotated_counterclockwise)

    # Convert BGR to RGB for displaying
    rotated_clockwise_rgb = cv2.cvtColor(rotated_clockwise, cv2.COLOR_BGR2RGB)
    rotated_counterclockwise_rgb = cv2.cvtColor(rotated_counterclockwise, cv2.COLOR_BGR2RGB)

    # Display images
    plt.figure(figsize=(10,5))

    plt.subplot(1,2,1)
    plt.imshow(rotated_clockwise_rgb)
    plt.title("90° Clockwise")
    plt.axis("off")

    plt.subplot(1,2,2)
    plt.imshow(rotated_counterclockwise_rgb)
    plt.title("90° Counterclockwise")
    plt.axis("off")

    plt.show()

    # Download the rotated images
    files.download("rotated_clockwise.jpg")
    files.download("rotated_counterclockwise.jpg")