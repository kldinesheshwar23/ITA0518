import cv2
import numpy as np
from google.colab import files
import matplotlib.pyplot as plt

# Upload image
uploaded = files.upload()

# Get uploaded file name
image_path = list(uploaded.keys())[0]

# Read image
img = cv2.imread(image_path)

# Check if image is loaded
if img is None:
    print("Error: Image not found!")
else:
    # Get image dimensions
    rows, cols = img.shape[:2]

    # Source points
    src_points = np.float32([
        [0, 0],
        [cols - 1, 0],
        [0, rows - 1],
        [cols - 1, rows - 1]
    ])

    # Destination points
    dst_points = np.float32([
        [0, 0],
        [cols - 1, 0],
        [int(0.33 * cols), rows - 1],
        [int(0.66 * cols), rows - 1]
    ])

    # Compute perspective transformation matrix
    M = cv2.getPerspectiveTransform(src_points, dst_points)

    # Apply perspective transformation
    perspective_img = cv2.warpPerspective(img, M, (cols, rows))

    # Save output image
    cv2.imwrite("Perspective_Transformed_Image.jpg", perspective_img)

    # Convert BGR to RGB for display
    original_rgb = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
    transformed_rgb = cv2.cvtColor(perspective_img, cv2.COLOR_BGR2RGB)

    # Display images
    plt.figure(figsize=(10, 5))

    plt.subplot(1, 2, 1)
    plt.imshow(original_rgb)
    plt.title("Original Image")
    plt.axis("off")

    plt.subplot(1, 2, 2)
    plt.imshow(transformed_rgb)
    plt.title("Perspective Transformed Image")
    plt.axis("off")

    plt.show()

    # Download the transformed image
    files.download("Perspective_Transformed_Image.jpg")