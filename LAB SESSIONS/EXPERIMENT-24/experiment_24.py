import cv2
import numpy as np
from google.colab import files
from google.colab.patches import cv2_imshow

# Upload image
uploaded = files.upload()

# Get uploaded image name
filename = next(iter(uploaded))

# Read image
image = cv2.imread(filename)

# Check image
if image is None:
    print("Error: Image could not be loaded.")
else:

    # High Boost Filter
    def high_boost_filter(image, boost_factor):
        kernel_size = 3

        # Create averaging kernel
        kernel = np.ones(
            (kernel_size, kernel_size),
            dtype=np.float32
        ) / (kernel_size ** 2)

        # Blur the image
        blur_image = cv2.filter2D(image, -1, kernel)

        # Convert to float for calculation
        image_float = image.astype(np.float32)
        blur_float = blur_image.astype(np.float32)

        # High boost filtering
        mask = image_float + boost_factor * (image_float - blur_float)

        # Keep pixel values between 0 and 255
        mask = np.clip(mask, 0, 255)

        return mask.astype(np.uint8)

    # Apply High Boost Filter
    sharpened_image = high_boost_filter(image, 1.5)

    # Display Original Image
    print("Original Image:")
    cv2_imshow(image)

    # Display High Boost Filtered Image
    print("High Boost Filtered Image:")
    cv2_imshow(sharpened_image)

    # Save output
    cv2.imwrite("/content/sharpened_image.jpg", sharpened_image)

    print("Output saved as sharpened_image.jpg")